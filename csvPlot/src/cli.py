#!python3
# This script reads csv files exported from the UNICORN control software
# used by GE/Cytiva Akta FPLCs, and plots the data for further analysis.
import argparse as ap
import logging
from .process import *

logger = logging.getLogger(__name__)

def main():
	# parse arguments
	ps = ap.ArgumentParser(prog="fplcPlot",description="A python script to parse csv \
		files generated by the UNICORN control software for Akta FPLCs and plot it.",
		epilog="'akta' akta UV-Vis spectrometer data, and 'caryuv': Cary UV-Vis spectrometer.")
	ps.add_argument('-i','--instrument',nargs=1,help="'akta' or 'caryuv'. Supported instrument which generated this data.")
	ps.add_argument('-d','--debug',action='store_true'),
	ps.add_argument('filepath',nargs="?",help="Path to the csv file.")
	args = ps.parse_args()

	# call out to the imports from process.py to process the data.
	if args.debug:
		logger.setLevel('DEBUG')
	else:
		logger.setLevel('WARNING')
	process(args.filepath,args.instrument[0])

if __name__ == "__main__":
	main()
